from .browser import (
    CONNECTION_ERRORS,
    CONNECTION_LOST,
    BiDiBrowser,
    needs_restart,
    read_message,
    remove_profile,
)
from ._page_fit_common import DEFAULT_MAX_PIXELS
from .search_utils import find_firefox
from . import _firefox_page_fit, _selector
from ..exceptions import (
    BrowserError,
    BrowserTimeoutError,
    PageLoadError,
    PageLoadTimeoutError,
)

import base64
import json
import logging
import os
from pathlib import Path
import socket
import subprocess
import tempfile
import time
from urllib.parse import urlparse

from websocket import WebSocketTimeoutException, create_connection

logger = logging.getLogger(__name__)

BIDI_TIMEOUT = 30

# A Firefox that starts well answers session.new in less than a second, see
# `_connect_ws()`.
SESSION_TIMEOUT = 10

DOWNLOAD_EVENT = 'browsingContext.downloadWillBegin'

CM_PER_INCH = 2.54

# Firefox refuses to capture an area larger than this number of pixels, in
# width or in height.
MAX_CAPTURE_SIZE = 65535


class FirefoxBiDi(BiDiBrowser):
    """Firefox backend using the WebDriver BiDi protocol.

    Connects directly to Firefox's BiDi WebSocket endpoint
    (ws://127.0.0.1:<port>/session) without requiring geckodriver.

    Known limitations:
    - Transparent PNG backgrounds for standalone SVG files may render as
      opaque white instead of transparent. This is a BiDi protocol limitation.
    """

    def __init__(
        self,
        executable=None,
        flags=None,
        print_command=False,
        bidi_port=None,
        disable_logging=False,
        allow_scripts_to_read_files=False,
    ):
        self.executable = executable
        if not flags:
            self.flags = []
        else:
            self.flags = [flags] if isinstance(flags, str) else list(flags)

        self.print_command = print_command
        self._bidi_port = bidi_port
        self._disable_logging = disable_logging
        self.allow_scripts_to_read_files = allow_scripts_to_read_files

        self.proc = None
        self._ws = None
        self._session_id = None
        self._context_id = None
        self._profile_dir = None
        self._current_port = None
        self._downloads_reported = False
        self._message_id = 0

    @property
    def executable(self):
        return self._executable

    @executable.setter
    def executable(self, value):
        self._executable = find_firefox(value)

    @property
    def disable_logging(self):
        return self._disable_logging

    @disable_logging.setter
    def disable_logging(self, value):
        self._disable_logging = value

    @staticmethod
    def _normalize_input(input_value):
        if os.path.exists(input_value):
            return Path(input_value).resolve().as_uri()
        parsed = urlparse(input_value)
        if parsed.scheme:
            return input_value
        return input_value

    def _pick_port(self):
        if self._bidi_port is not None:
            return self._bidi_port
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as sock:
            sock.bind(('127.0.0.1', 0))
            return int(sock.getsockname()[1])

    def _write_profile_prefs(self, profile_dir):
        Path(profile_dir).mkdir(parents=True, exist_ok=True)
        # When security.fileuri.strict_origin_policy is true (Firefox's
        # default), a file:// page cannot read other local files. Firefox
        # sets it to false when it is controlled remotely, as here (see
        # RecommendedPreferences.sys.mjs in Firefox's source). A value in
        # user.js overrides that, so we set it back to true unless
        # allow_scripts_to_read_files is enabled.
        strict_origin = 'false' if self.allow_scripts_to_read_files else 'true'
        # By default, Firefox would save the files that a URL downloads in the
        # user's Downloads folder. They are saved in the profile instead, which
        # is deleted once Firefox is closed.
        download_dir = json.dumps(os.path.join(profile_dir, 'downloads'))
        prefs = [
            '// File generated by html2image',
            'user_pref("devtools.chrome.enabled", true);',
            'user_pref("devtools.debugger.prompt-connection", false);',
            'user_pref("devtools.debugger.remote-enabled", true);',
            'user_pref("remote.active-protocols", 3);',
            'user_pref("fission.bfcacheInParent", false);',
            'user_pref("fission.webContentIsolationStrategy", 0);',
            f'user_pref("security.fileuri.strict_origin_policy", {strict_origin});',
            'user_pref("browser.download.folderList", 2);',
            f'user_pref("browser.download.dir", {download_dir});',
        ]
        Path(profile_dir, 'user.js').write_text(
            '\n'.join(prefs) + '\n', encoding='utf-8'
        )

    def _start_firefox(self):
        if self.proc is not None and self.proc.poll() is None:
            return

        self._profile_dir = tempfile.mkdtemp(prefix='html2image_firefox_bidi_')
        self._write_profile_prefs(self._profile_dir)
        self._current_port = self._pick_port()

        command = [
            str(self.executable),
            '--headless',
            '-no-remote',
            '--new-instance',
            '--profile', self._profile_dir,
            f'--remote-debugging-port={self._current_port}',
            *self.flags,
            'about:blank',
        ]

        if self.print_command:
            print(' '.join(command))

        if not self.disable_logging:
            logger.info(
                'Starting headless Firefox with --remote-debugging-port=%s.',
                self._current_port,
            )

        popen_kwargs = {}
        if self.disable_logging:
            popen_kwargs['stdout'] = subprocess.DEVNULL
            popen_kwargs['stderr'] = subprocess.DEVNULL

        creationflags = 0
        if os.name == 'nt':
            creationflags = getattr(subprocess, 'CREATE_NEW_PROCESS_GROUP', 0)
            creationflags |= getattr(subprocess, 'CREATE_NO_WINDOW', 0)

        self.proc = subprocess.Popen(
            command,
            creationflags=creationflags,
            **popen_kwargs,
        )

    def _bidi_send(self, method, **params):
        self._message_id += 1
        payload = {
            'id': self._message_id,
            'method': method,
            'params': params,
        }
        try:
            self._ws.send(json.dumps(payload))
        except CONNECTION_ERRORS as error:
            raise BrowserError(CONNECTION_LOST) from error
        return self._message_id

    def _bidi_recv_until(self, predicate, timeout=BIDI_TIMEOUT):
        deadline = time.time() + timeout
        while time.time() < deadline:
            remaining = max(0.1, deadline - time.time())
            self._ws.settimeout(remaining)
            try:
                raw = self._ws.recv()
            except WebSocketTimeoutException as exc:
                raise BrowserTimeoutError(
                    f'Timed out after {timeout}s waiting for BiDi message'
                ) from exc
            except CONNECTION_ERRORS as error:
                raise BrowserError(CONNECTION_LOST) from error
            message = read_message(raw)
            matched = predicate(message)
            if matched:
                return matched
        raise BrowserTimeoutError(
            f'Timed out after {timeout}s waiting for matching BiDi message'
        )

    def _bidi_expect_ok(self, message_id, timeout=BIDI_TIMEOUT):
        message = self._bidi_recv_until(
            lambda m: m if m.get('id') == message_id else None,
            timeout=timeout,
        )
        if message.get('type') == 'error' or 'error' in message:
            raise BrowserError(f'BiDi error for id={message_id}: {message}')
        return message

    def _connect_ws(self):
        """Start Firefox, connect to its BiDi WebSocket and open a session.

        Firefox answers session.new once its first window has started.
        Sometimes that window never finishes starting, and Firefox never
        answers. If Firefox does not give the session in time, it will be
        closed, and started once more, with more time to answer.
        """
        try:
            self._start_session(SESSION_TIMEOUT)
        except BrowserTimeoutError:
            if self._session_id is not None:
                # Firefox started, and is only slow.
                raise
            logger.debug(
                'Firefox did not finish starting. Starting it again.',
                exc_info=True,
            )
            self.__exit__()
            self._start_session(BIDI_TIMEOUT)

    def _start_session(self, timeout):
        """Start Firefox, connect to its BiDi WebSocket and open a session,
        waiting at most `timeout` seconds for it, see `_connect_ws()`.

        The connection will be retried while Firefox starts, but not the
        session: Firefox keeps a session when its connection closes, and
        would refuse any new one.
        """
        self._start_firefox()

        ws_url = f'ws://127.0.0.1:{self._current_port}/session'
        max_retries = 40
        retry_delay = 0.5

        for attempt in range(max_retries):
            try:
                # Firefox refuses a connection that sends an Origin header,
                # unless it was started with --remote-allow-origins.
                self._ws = create_connection(
                    ws_url, timeout=10, suppress_origin=True
                )
                break
            except CONNECTION_ERRORS as error:
                if self.proc.poll() is not None:
                    raise BrowserError(
                        f'Firefox exited with code {self.proc.returncode} '
                        'before accepting the connection.'
                    ) from error
                if attempt == max_retries - 1:
                    raise BrowserError(
                        'Could not connect to Firefox BiDi on port '
                        f'{self._current_port} after {max_retries} attempts.'
                    ) from error
                logger.debug(
                    'BiDi connection attempt %d/%d failed: %s. '
                    'Retrying in %.1fs...',
                    attempt + 1, max_retries, error, retry_delay,
                )
                time.sleep(retry_delay)

        logger.debug('Connected to Firefox BiDi WebSocket.')
        self._new_session(timeout)

    def _new_session(self, timeout):
        status_id = self._bidi_send('session.status')
        self._bidi_expect_ok(status_id, timeout=10)

        session_response = self._bidi_expect_ok(
            self._bidi_send('session.new', capabilities={'alwaysMatch': {}}),
            timeout=timeout,
        )
        self._session_id = session_response['result']['sessionId']

        # Firefox 144 and later report when a URL starts a download, see
        # `_navigate()`. Older versions refuse this event.
        try:
            self._bidi_expect_ok(
                self._bidi_send(
                    'session.subscribe',
                    events=[DOWNLOAD_EVENT],
                ),
                timeout=10,
            )
            self._downloads_reported = True
        except BrowserError:
            logger.debug('This version of Firefox does not report downloads.')
            self._downloads_reported = False

        contexts = self._get_tree()
        if contexts:
            self._context_id = str(contexts[0]['context'])
        else:
            self._context_id = self._create_context()

    def _get_tree(self):
        response = self._bidi_expect_ok(self._bidi_send('browsingContext.getTree'))
        return list(response['result'].get('contexts', []))

    def _create_context(self):
        response = self._bidi_expect_ok(
            self._bidi_send('browsingContext.create', type='tab'),
            timeout=20,
        )
        return str(response['result']['context'])

    def _set_viewport(self, width, height):
        self._bidi_expect_ok(
            self._bidi_send(
                'browsingContext.setViewport',
                context=self._context_id,
                viewport={'width': width, 'height': height},
                devicePixelRatio=1,
            ),
            timeout=20,
        )

    def _navigate(self, url):
        """Load `url` in the page.

        An error answer from Firefox means that the page could not be
        loaded, as with Chrome. A URL that starts a download leaves the
        previous page, which Firefox does not report as an error.
        """
        navigate_id = self._bidi_send(
            'browsingContext.navigate',
            context=self._context_id,
            url=url,
            wait='complete',
        )
        # The contexts in which a download started. The navigation ID that
        # Firefox gives with a download does not always match its answer.
        downloads = []

        def answer_to(message_id):
            def is_answer(message):
                if message.get('method') == DOWNLOAD_EVENT:
                    downloads.append(message['params']['context'])
                return message if message.get('id') == message_id else None
            return is_answer

        try:
            message = self._bidi_recv_until(
                answer_to(navigate_id), timeout=BIDI_TIMEOUT
            )
        except BrowserTimeoutError as error:
            raise PageLoadTimeoutError(str(error)) from error
        if message.get('type') == 'error' or 'error' in message:
            raise PageLoadError(f'BiDi error for id={navigate_id}: {message}')

        if self._downloads_reported:
            # Firefox can report the download just after its answer to the
            # navigation, so it is left the time to answer one more command.
            self._bidi_recv_until(answer_to(self._bidi_send('session.status')))
        if self._context_id in downloads:
            raise PageLoadError(
                'Navigation failed: the URL started a download instead of '
                'loading a page.'
            )

    def _evaluate(self, expression):
        """Return the value of a JavaScript expression that returns JSON."""
        response = self._bidi_expect_ok(
            self._bidi_send(
                'script.evaluate',
                expression=expression,
                target={'context': self._context_id},
                awaitPromise=True,
            ),
        )
        result = response['result']
        if result['type'] == 'exception':
            raise BrowserError(
                f'JavaScript error: {result["exceptionDetails"]["text"]}'
            )
        return json.loads(result['result']['value'])

    def _capture(self, output_file_path, origin='viewport', clip=None):
        """Save an image of the viewport, or of the `clip` area.

        The coordinates of `clip` are relative to `origin`, 'viewport' or
        'document'.
        """
        ext = os.path.splitext(output_file_path)[1].lower()
        format_type = 'image/jpeg' if ext in ('.jpg', '.jpeg') else 'image/png'
        area = {'clip': {'type': 'box', **clip}} if clip else {}

        response = self._bidi_expect_ok(
            self._bidi_send(
                'browsingContext.captureScreenshot',
                context=self._context_id,
                origin=origin,
                format={'type': format_type},
                **area,
            ),
            timeout=30,
        )
        Path(output_file_path).write_bytes(base64.b64decode(response['result']['data']))

    def _capture_from_viewport(self, output_file_path, box, clip):
        """Save an image of `clip`, scrolling the page to show it if needed.

        The page is left scrolled. Returns False, without saving anything, if
        `clip` does not fit in the viewport.
        """
        scroll = _selector.viewport_scroll(box, clip)
        if scroll is None:
            return False

        scroll_x, scroll_y = self._evaluate(_selector.scroll_js(*scroll))
        self._capture(
            output_file_path,
            'viewport',
            {**clip, 'x': clip['x'] - scroll_x, 'y': clip['y'] - scroll_y},
        )
        return True

    def _capture_elements(self, output_path, elements, padding):
        """Save an image of each element, see `screenshot()`."""
        _selector.check_selectors(
            self._evaluate, [selector for selector, _ in elements]
        )

        missing, too_large = [], []
        for element in elements:
            selector, output_file = element
            output_file_path = os.path.join(output_path, output_file)
            # The page is scrolled back as loaded after each element, so
            # that each image is the same as with one call per selector.
            box = self._evaluate(_selector.element_box_js(selector))
            clip = _selector.element_clip(box, padding)
            if clip is None:
                missing.append(element)
            elif max(clip['width'], clip['height']) > MAX_CAPTURE_SIZE:
                too_large.append(element)
            # Firefox only captures from the document what is inside of the
            # root element. On a page without doctype, the root element can
            # be much smaller than the page: the element is then captured
            # from the viewport.
            elif (
                clip['x'] + clip['width'] <= box['rootWidth']
                and clip['y'] + clip['height'] <= box['rootHeight']
            ):
                self._capture(output_file_path, 'document', clip)
            elif not self._capture_from_viewport(output_file_path, box, clip):
                too_large.append(element)
            if box is not None:
                self._evaluate(_selector.restore_js(selector, box))
        return missing, too_large

    def _print(self, output_file_path, options):
        # BiDi lengths are in centimeters.
        top, right, bottom, left = (
            length * CM_PER_INCH for length in options['margin']
        )
        response = self._bidi_expect_ok(
            self._bidi_send(
                'browsingContext.print',
                context=self._context_id,
                page={
                    'width': options['width'] * CM_PER_INCH,
                    'height': options['height'] * CM_PER_INCH,
                },
                margin={
                    'top': top, 'right': right, 'bottom': bottom, 'left': left,
                },
                background=options['background'],
                scale=options['scale'],
                # Firefox ignores the scale while it shrinks wide pages
                # to fit the paper.
                shrinkToFit=options['scale'] == 1,
            ),
            timeout=30,
        )
        Path(output_file_path).write_bytes(base64.b64decode(response['result']['data']))

    def _shutdown_process_tree(self):
        if self.proc is None or self.proc.poll() is not None:
            return

        if os.name == 'nt':
            subprocess.run(
                ['taskkill', '/PID', str(self.proc.pid), '/T'],
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL,
                check=False,
            )
            try:
                self.proc.wait(timeout=5)
                return
            except subprocess.TimeoutExpired:
                pass
            subprocess.run(
                ['taskkill', '/PID', str(self.proc.pid), '/T', '/F'],
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL,
                check=False,
            )
            try:
                self.proc.wait(timeout=5)
            except subprocess.TimeoutExpired:
                pass
        else:
            self.proc.terminate()
            try:
                self.proc.wait(timeout=5)
            except subprocess.TimeoutExpired:
                self.proc.kill()
                try:
                    self.proc.wait(timeout=5)
                except subprocess.TimeoutExpired:
                    pass

    def screenshot(
        self,
        input,
        output_path,
        output_file='screenshot.png',
        size=(1920, 1080),
        pdf_options=None,
        elements=None,
        selector_padding=0,
        full_page=False,
        full_page_stability_timeout=None,
        full_page_profile='balanced',
        full_page_fixed_elements='auto',
        full_page_max_pixels=DEFAULT_MAX_PIXELS,
    ):
        """Take a screenshot using Firefox via WebDriver BiDi.

        If `pdf_options` is given, the page is printed to a PDF instead.

        If `elements` is given, an image of each element is saved instead,
        as with `ChromeCDP.screenshot()`.

        If `full_page` is True, an image of the whole page will be saved
        instead, see `_firefox_page_fit.capture_full_page()`.
        """
        target_url = self._normalize_input(input)
        auto_started = self._ws is None
        if auto_started:
            self.__enter__()

        try:
            width, height = size if size else (1920, 1080)

            self._set_viewport(width, height)
            self._navigate(target_url)
            if pdf_options is not None:
                self._print(os.path.join(output_path, output_file), pdf_options)
            elif elements is not None:
                return self._capture_elements(
                    output_path, elements, selector_padding
                )
            elif full_page:
                _firefox_page_fit.capture_full_page(
                    self,
                    output_path,
                    output_file,
                    width,
                    height,
                    stability_timeout=full_page_stability_timeout,
                    profile=full_page_profile,
                    fixed_elements=full_page_fixed_elements,
                    max_pixels=full_page_max_pixels,
                )
            else:
                self._capture(os.path.join(output_path, output_file))
        except Exception as error:
            if not auto_started and needs_restart(error):
                self.__exit__()
                self.__enter__()
            raise
        finally:
            if auto_started:
                self.__exit__()

    def __enter__(self):
        """Start Firefox and establish a BiDi session."""
        try:
            self._connect_ws()
            return self
        except Exception:
            self.__exit__()
            raise

    def __exit__(self, *exc):
        """Close the BiDi session and shut down Firefox."""
        if not self.disable_logging:
            logger.info(
                'Closing Firefox BiDi instance on port %s.',
                self._current_port,
            )

        if self._ws:
            # browser.close also ends the session. Firefox closes the
            # connection once it has answered, then exits. If Firefox
            # refuses the command, or does not exit in time, it is stopped
            # below.
            try:
                close_id = self._bidi_send('browser.close')
                self._bidi_expect_ok(close_id, timeout=10)
                self.proc.wait(timeout=5)
            except Exception:
                logger.debug('Firefox did not close by itself.', exc_info=True)
            try:
                self._ws.close()
            except Exception:
                pass
            finally:
                self._ws = None
                self._session_id = None
                self._context_id = None

        self._shutdown_process_tree()
        self.proc = None

        if self._profile_dir:
            remove_profile(self._profile_dir)
            self._profile_dir = None
